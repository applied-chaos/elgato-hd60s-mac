"""Emit a C header with the data tables the driver needs, read from the user's own libUB530.dylib.

Usage: python3 -I tools/extract-tables.py path/to/libUB530.dylib > build/ub530_tables.h
"""
import hashlib
import sys

SHA256 = "8a5c35d4531457907bff6f047111899d2a5cfea2dfc98e859d4d1ee982408d3e"

# name: (file offset, length). File offsets equal VM addresses in this dylib.
TABLES = {
    "csc_rgb": (0x28730, 16),
    "csc_rgb_tail": (0x28740, 8),
    "csc_601": (0x28750, 16),
    "csc_601_tail": (0x28760, 2),
    "csc_709": (0x28770, 16),
    "csc_709_tail": (0x28780, 2),
    "tx_phase": (0x28782, 6),
}


def main() -> None:
    if len(sys.argv) != 2 or not sys.argv[1]:
        sys.exit("usage: extract-tables.py libUB530.dylib (from Game Capture HD 2.11.14)")
    data = open(sys.argv[1], "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"{sys.argv[1]}: sha256 {digest} does not match Game Capture HD 2.11.14")
    print("/* Generated by tools/extract-tables.py from libUB530.dylib. Do not commit. */")
    print("#pragma once")
    print("#include <stdint.h>")
    for name, (off, n) in TABLES.items():
        body = ", ".join(f"0x{b:02x}" for b in data[off : off + n])
        print(f"static const uint8_t ub530_{name}[{n}] = {{{body}}};")


main()
